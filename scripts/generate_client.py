#!/usr/bin/env python3
"""Writes src/socialapihq/client.py, the `SocialAPI` client, from the OpenAPI spec.

One attribute per network (`client.tiktok`), one method per endpoint named after its
path (`client.tiktok.post_comment_replies(...)`), each calling the generated API class
and turning a refusal into a `SocialAPIError`. Also exports both from the package.
"""

from __future__ import annotations

from pathlib import Path

from spec import Endpoint, api_class, api_module, attribute, endpoints, load, tags_in_order

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "socialapihq"

HEADER = '''"""The SocialAPI client: one attribute per network, one method per endpoint.

Generated by scripts/generate_client.py from the OpenAPI spec. Do not edit by hand.
"""

from __future__ import annotations

import json
import os
from typing import Any, Callable, Optional, TypeVar

import urllib3

from socialapihq.api_client import ApiClient
from socialapihq.configuration import Configuration
from socialapihq.exceptions import ApiException
{imports}

T = TypeVar("T")


class SocialAPIError(Exception):
    """A request SocialAPI refused or could not answer. Refusals cost no credits.

    - ``status``: the HTTP status (404, 403, 402, 429, 502…), 0 when the network failed.
    - ``code``: what kind (``NOT_FOUND``, ``PRIVATE``, ``INVALID_REQUEST``,
      ``INSUFFICIENT_CREDITS``, ``RATE_LIMITED``, ``UPSTREAM_UNAVAILABLE``…), stable to
      branch on.
    - ``param``: the parameter at fault, for ``INVALID_REQUEST``.
    - ``request_id``: quote it to support.
    - ``retry_after``: seconds to wait, for ``RATE_LIMITED``.
    """

    def __init__(
        self,
        message: str,
        *,
        status: int,
        code: str,
        param: Optional[str] = None,
        request_id: Optional[str] = None,
        retry_after: Optional[int] = None,
    ) -> None:
        super().__init__(message)
        self.message = message
        self.status = status
        self.code = code
        self.param = param
        self.request_id = request_id
        self.retry_after = retry_after

    def __repr__(self) -> str:
        return f"SocialAPIError(status={{self.status}}, code={{self.code!r}}, message={{self.message!r}})"


def _header(headers: Any, name: str) -> Optional[str]:
    if not headers:
        return None
    for key, value in dict(headers).items():
        if key.lower() == name:
            return str(value)
    return None


def _call(request: Callable[..., T], **params: Any) -> T:
    try:
        return request(**{{k: v for k, v in params.items() if v is not None}})
    except ApiException as error:
        body: dict[str, Any] = {{}}
        try:
            parsed = json.loads(error.body) if error.body else {{}}
            body = parsed if isinstance(parsed, dict) else {{}}
        except (TypeError, ValueError):
            pass
        retry = _header(error.headers, "retry-after")
        raise SocialAPIError(
            body.get("error") or f"SocialAPI answered {{error.status}}.",
            status=int(error.status or 0),
            code=body.get("code") or "ERROR",
            param=body.get("param"),
            request_id=_header(error.headers, "x-request-id"),
            retry_after=int(retry) if retry and retry.isdigit() else None,
        ) from None
    except urllib3.exceptions.HTTPError as error:
        raise SocialAPIError(
            f"Could not reach SocialAPI: {{error}}.", status=0, code="NETWORK_ERROR"
        ) from error
'''


def method(endpoint: Endpoint) -> str:
    arguments = ["self"]
    if endpoint.params:
        arguments.append("*")
    for param in sorted(endpoint.params, key=lambda p: not p.required):
        if param.required:
            arguments.append(f"{param.python}: {param.type}")
        else:
            arguments.append(f"{param.python}: Optional[{param.type}] = None")
    returns = endpoint.returns or "Any"
    doc = [endpoint.summary, "", f"``GET {endpoint.path}``"]
    if endpoint.params:
        doc += ["", "Args:"]
        doc += [f"    {p.python}: {p.description}" for p in endpoint.params]
    docstring = "\n        ".join(line for line in doc).replace('"""', "'''")
    passed = ", ".join(f"{p.python}={p.python}" for p in endpoint.params)
    call = f"_call(self._api.{endpoint.generated}, _request_timeout=self._timeout{', ' + passed if passed else ''})"
    return (
        f"    def {endpoint.method}({', '.join(arguments)}) -> {returns}:\n"
        f'        """{docstring}\n        """\n'
        f"        return {call}\n"
    )


def render(items: list[Endpoint]) -> str:
    tags = tags_in_order(items)
    imports = [f"from socialapihq.api.{api_module(tag)} import {api_class(tag)}" for tag in tags]
    models = sorted({e.returns for e in items if e.returns})
    imports.append("from socialapihq.models import (\n" + "".join(f"    {m},\n" for m in models) + ")")
    out = [HEADER.format(imports="\n".join(imports))]
    for tag in tags:
        name = api_class(tag).removesuffix("Api") + "Endpoints"
        what = "Your workspace" if tag == "Account" else f"{tag}'s endpoints"
        out.append(
            f"\n\nclass {name}:\n"
            f'    """{what}, as ``client.{attribute(tag)}``."""\n\n'
            f"    def __init__(self, api: {api_class(tag)}, timeout: Optional[float]) -> None:\n"
            f"        self._api = api\n"
            f"        self._timeout = timeout\n"
        )
        for endpoint in (e for e in items if e.tag == tag):
            out.append("\n" + method(endpoint))
    fields = "".join(
        f"        self.{attribute(tag)} = {api_class(tag).removesuffix('Api')}Endpoints({api_class(tag)}(self._client), timeout)\n"
        for tag in tags
    )
    out.append(
        f'''

class SocialAPI:
    """The SocialAPI client: one attribute per network, one method per endpoint.

    ::

        client = SocialAPI(api_key=os.environ["SOCIALAPI_API_KEY"])
        profile = client.tiktok.profile(handle="nike").data

    A refusal (404, 403, 402, 429…) raises a ``SocialAPIError`` with its ``status`` and
    ``code``. Refusals cost no credits.

    Args:
        api_key: Your API key (``sapi_…``). Defaults to the ``SOCIALAPI_API_KEY``
            environment variable.
        base_url: Defaults to ``https://api.socialapi.sh``.
        timeout: Seconds to wait for each answer; none by default.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        *,
        base_url: str = "https://api.socialapi.sh",
        timeout: Optional[float] = None,
    ) -> None:
        key = api_key or os.environ.get("SOCIALAPI_API_KEY")
        if not key:
            raise ValueError("Pass your API key as SocialAPI(api_key=...), or set SOCIALAPI_API_KEY.")
        self._client = ApiClient(Configuration(host=base_url.rstrip("/"), access_token=key))
{fields}
    def close(self) -> None:
        """Closes the connections the client keeps."""
        self._client.rest_client.pool_manager.clear()

    def __enter__(self) -> "SocialAPI":
        return self

    def __exit__(self, *_: object) -> None:
        self.close()
'''
    )
    return "".join(out)


def main() -> None:
    items = endpoints(load())
    (PACKAGE / "client.py").write_text(render(items), encoding="utf-8")

    init = PACKAGE / "__init__.py"
    text = init.read_text(encoding="utf-8")
    export = "\n# The client most code needs (scripts/generate_client.py).\nfrom socialapihq.client import SocialAPI as SocialAPI, SocialAPIError as SocialAPIError\n__all__ += [\"SocialAPI\", \"SocialAPIError\"]\n"
    if "socialapihq.client import SocialAPI" not in text:
        init.write_text(text.rstrip("\n") + "\n" + export, encoding="utf-8")
    print(f"Wrote src/socialapihq/client.py ({len(items)} endpoints).")


if __name__ == "__main__":
    main()
