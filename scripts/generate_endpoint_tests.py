#!/usr/bin/env python3
"""Writes tests/test_endpoints.py from the spec: every endpoint has its method on the
client, and calling it sends `GET <path>` with the API key."""

from __future__ import annotations

from pathlib import Path

from spec import attribute, endpoints, load

TESTS = Path(__file__).resolve().parent.parent / "tests" / "test_endpoints.py"

SAMPLES = {"str": '"x"', "int": "1", "float": "1.0", "bool": "True"}


def main() -> None:
    cases = []
    for e in endpoints(load()):
        arguments = ", ".join(f"{p.python}={SAMPLES[p.type]}" for p in e.params if p.required)
        cases.append(f'    ("client.{attribute(e.tag)}.{e.method}", "{e.path}", lambda c: c.{attribute(e.tag)}.{e.method}({arguments})),')
    TESTS.write_text(
        '''# Generated by scripts/generate_endpoint_tests.py from the OpenAPI spec. Do not edit by hand.
import pytest

from stub import stubbed

ENDPOINTS = [
'''
        + "\n".join(cases)
        + '''
]


@pytest.mark.parametrize(("name", "path", "invoke"), ENDPOINTS, ids=[e[0] for e in ENDPOINTS])
def test_sends_get_with_the_key(name, path, invoke):
    client, requests = stubbed(200, {"data": [], "pagination": {"hasMore": False}})
    try:
        invoke(client)
    except Exception:  # noqa: BLE001 - the stub's body need not fit the model
        pass
    assert len(requests) == 1, name
    method, url, headers = requests[0]
    assert method == "GET"
    assert url.split("?")[0] == "https://api.socialapi.sh" + path
    assert headers["Authorization"] == "Bearer sapi_test"
''',
        encoding="utf-8",
    )
    print(f"Wrote tests/test_endpoints.py ({len(cases)} endpoints).")


if __name__ == "__main__":
    main()
